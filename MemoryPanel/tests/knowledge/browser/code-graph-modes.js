// Deterministic HTTP fixture + actual production CodePage; not SDK extraction proof.
async (page) => {
  const checks = [];
  const assert = (ok, message) => { if (!ok) throw new Error(message); checks.push(message); };
  const control = changes => page.evaluate(changes => fetch('/__codegraph-test', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(changes) }).then(r => r.json()), changes);
  const requests = () => page.evaluate(() => fetch('/__codegraph-test').then(r => r.json()).then(s => s.requests));
  const work = page.getByTestId('code-graph-workspace');
  const relations = page.getByTestId('code-graph-relations');
  const source = page.getByTestId('code-graph-source');
  const mode = page.getByRole('combobox', { name: '关系视图', exact: true });
  const graphIdle = () => page.waitForFunction(() => { const root = document.querySelector('[data-testid="code-graph-workspace"]'); return root && !root.querySelector('.tea-icon-loading') && ![...root.querySelectorAll('button')].some(b => b.textContent === '加载更多关系' && b.disabled); });
  const search = async (query, label) => { await page.getByLabel('搜索符号', { exact: true }).fill(query); await page.getByLabel('搜索符号', { exact: true }).press('Enter'); await page.getByRole('button', { name: label, exact: true }).click(); await source.locator('pre').waitFor(); };
  const edgeRows = () => relations.locator('table').nth(1).locator('tbody tr');
  const waitRows = count => page.waitForFunction(count => document.querySelector('[data-testid="code-graph-relations"] table:nth-of-type(2) tbody')?.children.length === count, count);
  try {
    await page.evaluate(() => { localStorage.setItem('tdai-memory.lang','zh-CN'); localStorage.removeItem('codegraph-test-no-webgl'); });
    await page.reload();
    await page.setViewportSize({ width: 1600, height: 1100 });
    await control({ delayByAction: { 'graph-tree': 600 } });
    await page.getByRole('button', { name: 'call-fixture-alpha', exact: true }).click();
    await page.getByRole('tab', { name: '关系图', exact: true }).click();
    assert(await mode.isDisabled(), 'mode selector blocks premature switch while initial snapshot tree loads');
    await page.waitForFunction(() => !document.querySelector('select[aria-label="关系视图"]')?.disabled);
    await control({ delayByAction: {} });
    await search('entry', 'entry function src/main.ts:2');
    await page.getByRole('button', { name: '关系列表', exact: true }).click();
    await mode.selectOption('impact');
    await page.getByTestId('code-graph-impact-list').locator('tbody tr').nth(2).waitFor();
    assert((await source.innerText()).includes('src/main.ts:entry'), 'calls → impact retains the real selected symbol');
    assert(await page.getByRole('combobox', { name: '查询跳数' }).inputValue() === '2', 'impact starts at two hops');
    assert((await work.innerText()).includes('静态'), 'potential impact has explicit static-analysis caveat');
    const impact = page.getByTestId('code-graph-impact-list');
    assert(await impact.locator('tbody tr').count() === 3, 'impact list deduplicates three affected nodes');
    await impact.getByRole('button', { name: '查看 entry 的证据路径', exact: true }).click();
    const path = page.getByTestId('code-graph-path');
    assert((await path.innerText()).includes('entry → helper') && (await path.innerText()).includes('helper → entry'), 'two-hop impact evidence preserves affected → helper → focus direction');
    await path.getByRole('checkbox').check();
    assert(await relations.locator('table').first().locator('tbody tr').count() === 3, 'path-only view keeps the complete directed path');
    await path.getByRole('checkbox').uncheck();
    await page.getByRole('combobox', { name: '显示影响层级' }).selectOption('direct');
    assert(await impact.locator('tbody tr').count() === 2, 'direct layer filters indirect affected node');
    await page.getByRole('combobox', { name: '显示影响层级' }).selectOption('all');
    await page.getByRole('combobox', { name: '查询跳数' }).selectOption('1');
    await page.waitForFunction(() => document.querySelector('[data-testid="code-graph-impact-list"] tbody')?.children.length === 2);
    await page.getByRole('button', { name: '展开潜在影响', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[data-testid="code-graph-impact-list"] tbody')?.children.length === 3);
    const depthRequest = (await requests()).filter(r => r.path.endsWith('/graph') && r.body.mode === 'impact').at(-1).body;
    assert(depthRequest.nodeId.endsWith(':a') && depthRequest.depth === 2 && depthRequest.direction === 'in', 'impact expansion increases original focus radius, preserving depth meaning');
    await control({ modePages: true });
    await page.getByRole('combobox', { name: '查询跳数' }).selectOption('3');
    await page.getByRole('button', { name: '加载更多关系', exact: true }).click();
    await impact.getByRole('button', { name: '查看 entry 的证据路径', exact: true }).waitFor();
    assert(await impact.getByRole('button', { name: '查看 entry 的证据路径', exact: true }).isEnabled() && await impact.locator('tbody tr').count() === 3, 'impact continuation preserves previous paths and joins new evidence to prior-page edges');
    await control({ modePages: false });
    await mode.selectOption('hierarchy');
    await page.getByText('请选择 class 或 interface 类型；当前符号不适用于继承视图。', { exact: true }).waitFor();
    assert(true, 'non-type symbol retained with explicit hierarchy applicability hint');
    await search('Derived', 'Derived class src/types.ts:21');
    await waitRows(2);
    assert((await edgeRows().allTextContents()).some(t => t.includes('Derived') && t.includes('extends') && t.includes('Base')), 'hierarchy preserves class → parent direction');
    assert((await edgeRows().allTextContents()).some(t => t.includes('implements') && t.includes('Readable')), 'hierarchy keeps interface implementation as distinct relation');
    await work.getByRole('checkbox', { name: 'implements', exact: true }).uncheck();
    await waitRows(1);
    assert(!(await edgeRows().innerText()).includes('implements'), 'hierarchy relation filter queries only extends');
    await work.getByRole('checkbox', { name: 'implements', exact: true }).check();
    await waitRows(2);
    await search('ExternalChild', 'ExternalChild class src/external.ts:3');
    await page.getByTestId('code-graph-unresolved').waitFor();
    assert((await page.getByTestId('code-graph-unresolved').innerText()).includes('UnknownBase') && await edgeRows().count() === 0, 'unresolved external parent stays an explanatory record without fabricated edges');
    await search('Readable', 'Readable interface src/types.ts:2');
    await waitRows(1);
    assert((await work.innerText()).includes('未提取 TypeScript 接口继承关系'), 'real SDK interface inheritance limitation is explicit');
    await page.getByRole('button', { name: '展开父类型', exact: true }).click();
    await page.getByText('当前索引器未提取 TypeScript 接口继承关系；可查看类继承和接口实现关系', { exact: true }).waitFor();
    await page.getByRole('button', { name: '选择其他符号', exact: true }).waitFor();
    assert(true, 'unsupported interface parent extraction gives the specific extractor limitation and recovery action');
    await control({ clearRequests: true });
    await mode.selectOption('dependencies');
    await waitRows(2);
    assert((await work.innerText()).includes('声明位置') && (await edgeRows().allTextContents())[0].includes('×2'), 'dependencies show declaration-based import metric and aggregate edge count');
    await relations.locator('table').first().getByRole('button', { name: 'src', exact: true }).click();
    await page.getByTestId('code-graph-aggregate-details').waitFor();
    assert(!(await requests()).some(r => r.path.endsWith('/graph-source')), 'aggregate selection never requests fabricated node source');
    await page.getByTestId('code-graph-cycles').getByRole('button').click();
    assert((await source.innerText()).includes('src → lib') && (await source.innerText()).includes('lib → src'), 'confirmed module cycle exposes all original directed edges');
    await page.getByRole('button', { name: '下钻到文件', exact: true }).click();
    await waitRows(2);
    assert(await page.getByRole('combobox', { name: '聚合层级' }).inputValue() === 'file' && await page.getByLabel('依赖源范围', { exact: true }).inputValue() === 'src', 'module drilldown applies file aggregation and module source scope');
    await relations.locator('table').first().getByRole('button', { name: 'main.ts', exact: true }).click();
    await page.getByRole('button', { name: '查看文件内符号', exact: true }).click();
    await page.getByRole('button', { name: 'entry function src/main.ts:2', exact: true }).waitFor();
    assert(true, 'file drilldown searches actual symbols using file scope');
    await page.getByRole('button', { name: '返回焦点', exact: true }).click();
    await waitRows(2);
    assert(await page.getByRole('combobox', { name: '聚合层级' }).inputValue() === 'directory', 'dependency Back restores prior aggregation request');
    await edgeRows().first().getByRole('button').last().click();
    const evidence = page.getByTestId('code-graph-dependency-evidence');
    await evidence.getByRole('button').first().waitFor();
    await page.getByRole('button', { name: '加载更多证据', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[data-testid="code-graph-dependency-evidence"]')?.children.length === 2);
    assert(await evidence.locator('li').count() === 2, 'dependency evidence uses separate paginated deduplicated declaration list');
    await evidence.getByRole('button').first().click();
    await source.locator('pre').waitFor();
    assert((await source.innerText()).includes('cg-browser-a@v1:a'), 'dependency evidence resolves a real snapshot node before loading source');
    await evidence.getByRole('button').last().click();
    await page.waitForFunction(() => document.querySelector('[data-testid="code-graph-source"] ._codegraph-line')?.textContent === '700');
    assert((await requests()).filter(r => r.path.endsWith('/graph-source')).at(-1).body.sourceLine === 700 && (await source.getByRole('link').getAttribute('href')).includes('#L700-L700'), 'same-file evidence refreshes requested line beyond 300 and anchors immutable source link');
    await control({ delayByAction: { 'graph-node': 800 }, clearRequests: true });
    await evidence.getByRole('button').last().click();
    await page.getByRole('combobox', { name: '关系类型', exact: true }).selectOption('calls');
    await waitRows(2); await page.waitForTimeout(900);
    assert(!(await requests()).some(r => r.path.endsWith('/graph-source')), 'query reconfiguration cancels late graph-node response and prevents stale source revival');
    await control({ delayByAction: {}, modePages: true });
    await page.getByRole('combobox', { name: '关系类型', exact: true }).selectOption('imports');
    await page.getByRole('button', { name: '加载更多关系', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[data-testid="code-graph-relations"]')?.textContent.includes('×3'));
    assert(!(await relations.innerText()).includes('×5') && await edgeRows().count() === 2, 'cumulative aggregate continuation replaces counts and edges rather than adding them');
    await control({ modePages: false, dependencyPartial: true });
    await page.getByRole('combobox', { name: '关系类型', exact: true }).selectOption('calls');
    await waitRows(2);
    assert((await page.getByTestId('code-graph-cycles').innerText()).includes('尚未证实'), 'incomplete dependency scan does not claim the graph is acyclic');
    await control({ dependencyPartial: false });
    await mode.selectOption('calls');
    await source.locator('pre').waitFor();
    assert((await source.innerText()).includes('src/main.ts:entry'), 'return from aggregate view restores last inspected real symbol');
    await page.screenshot({ path: '/Users/zj/daydayup/TencentDB-Agent-Memory/output/playwright/codegraph-modes-desktop.png', fullPage: true });
    return { checks, browser: await page.context().browser().version() };
  } catch (error) {
    await page.screenshot({ path: '/Users/zj/daydayup/TencentDB-Agent-Memory/output/playwright/codegraph-modes-failure.png', fullPage: true });
    throw new Error(JSON.stringify({ checks, error: String(error) }));
  }
}
