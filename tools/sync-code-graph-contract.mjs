import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const source = readFileSync(new URL('contracts/code-graph.d.ts', root), 'utf8');
const output = '// Generated by tools/sync-code-graph-contract.mjs; edit contracts/code-graph.d.ts.\n' + source;
for (const path of ['MemoryKnowledge/src/contracts/code-graph.d.ts', 'MemoryPanel/src/panel/kernel/contracts/code-graph.d.ts', 'MemoryPanel/web/src/lib/api/code-graph-contract.d.ts']) {
  const file = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== output) throw new Error(`Contract drift: ${fileURLToPath(file)}`);
  } else writeFileSync(file, output);
}
